#[cfg(all(test, feature = "test-fixtures"))]
mod tests {
    use super::build_request_key;

    struct Brand(&'static [u8]);

    impl crate::surface::Runner for Brand {
        fn compile_snapshot(&self) -> bool {
            true
        }

        fn facade_plan(&self) -> Option<&[u8]> {
            Some(self.0)
        }
    }

    #[test]
    fn build_identity_reuses_rawr_snapshot_but_binds_compiler_facade() {
        let limits = crate::cargo::Limits::standard();
        let native = crate::input::proof::Proof::fixture();
        let profile = crate::profile::Proof::neutral();
        let mut first = crate::surface::Request::fixture(Brand(b"facade-a"), &limits);
        let mut body_edit = crate::surface::Request::fixture(Brand(b"facade-a"), &limits);
        first.snapshot = crate::surface::Snapshot::from_rawr_digest([1; 32]);
        body_edit.snapshot = crate::surface::Snapshot::from_rawr_digest([2; 32]);
        assert_eq!(
            build_request_key(&first, &native, &profile).expect("the first key seals"),
            build_request_key(&body_edit, &native, &profile).expect("the body-edit key seals")
        );

        let facade_edit = crate::surface::Request::fixture(Brand(b"facade-b"), &limits);
        assert_ne!(
            build_request_key(&first, &native, &profile).expect("the first key reseals"),
            build_request_key(&facade_edit, &native, &profile).expect("the facade-edit key seals")
        );
    }

    #[test]
    fn build_identity_excludes_current_application_semantic_but_full_proof_binds_it() {
        let limits = crate::cargo::Limits::standard();
        let native = crate::input::proof::Proof::fixture();
        let request = crate::surface::Request::fixture((), &limits);
        let first = crate::profile::Proof::neutral_with_application([1; 32]);
        let edited = crate::profile::Proof::neutral_with_application([2; 32]);

        assert_ne!(first.fingerprint(), edited.fingerprint());
        assert_eq!(first.owner_fingerprint(), edited.owner_fingerprint());
        assert_eq!(
            build_request_key(&request, &native, &first).expect("the first owner key seals"),
            build_request_key(&request, &native, &edited).expect("the edited owner key seals"),
        );
    }
}
