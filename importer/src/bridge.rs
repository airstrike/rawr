const REQUEST_SCHEMA: u32 = 12;
/// The generated runner's version: the source this module writes (the
/// runner's templates, its adapters and the bindings it emits for each
/// root), the build request key and the runner manifest's carrier. Bump it
/// when a change alters any file the generated runner holds. A bump
/// rebuilds runners and nothing upstream of them: classification
/// (`CLASSIFIER_VERSION`) and the bindings plan (the facade's `SCHEMA`)
/// keep their own versions and stay (#1766). An installed rawr's request
/// key also carries the rawr sources' digest (#1712), so there this
/// version matters for a development checkout and the store's eviction.
const GENERATOR_VERSION: u32 = 315;

/// Exact pre-build cache lookup identity.
#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub struct BuildRequestKey([u8; 32]);

/// Complete symbolic request before generated bytes are owned.
#[cfg(not(target_arch = "wasm32"))]
pub struct GenerationRequestKey<B> {
    request: crate::surface::Request<B>,
    native: crate::input::proof::Proof,
    profile: profile::Profile,
    revision: crate::supervisor::Revision,
    build: BuildRequestKey,
    /// The request's semantic digest (`generate::semantic_digest`), which
    /// its build request key and its rendering key share.
    semantic: [u8; 32],
}

impl BuildRequestKey {
    /// Borrow the complete pre-build digest.
    #[must_use]
    pub const fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }

    #[cfg(any(test, feature = "test-fixtures"))]
    pub(crate) const fn fixture(bytes: [u8; 32]) -> Self {
        Self(bytes)
    }
}

#[cfg(not(target_arch = "wasm32"))]
impl<B: crate::surface::Runner> Demand<Sealed, B> {
    /// Consume an exact demand and complete normal-build evidence into one
    /// generation request. No executable authority exists at this stage.
    pub fn request(
        self,
        native: crate::input::proof::Proof,
        profile: crate::profile::Proof,
        revision: crate::supervisor::Revision,
    ) -> Result<GenerationRequestKey<B>, request::Error> {
        let request = self.into_request();
        request.require_runner_profile(&profile)?;
        let (build, semantic) = keys(&request, &native, &profile)?;
        Ok(GenerationRequestKey {
            request,
            native,
            profile: profile.into(),
            revision,
            build,
            semantic,
        })
    }
}

#[cfg(not(target_arch = "wasm32"))]
impl<B: crate::surface::Runner> Demand<Sealed, B> {
    /// Continue explicitly owned Runner inputs with historical generated profile data.
    pub fn request_retained(
        self,
        native: crate::input::proof::Proof,
        pair: crate::composition::profile::Pair,
        revision: crate::supervisor::Revision,
    ) -> Result<GenerationRequestKey<B>, request::Error> {
        let request = self.into_request();
        request.require_retained_runner_profile(&pair)?;
        let (build, semantic) = keys(&request, &native, pair.proof.value())?;
        let profile = if matches!(&pair.demand, crate::node::staging::Owned::Current(_))
            && matches!(&pair.generated, crate::node::staging::Owned::Current(_))
        {
            profile::Profile::Current(
                pair.into_current()
                    .map_err(|error| {
                        request::Error::Node(Box::new(match error {
                            crate::profile::Error::Node(error) => *error,
                            error => crate::node::Error::Transform(error.to_string().into()),
                        }))
                    })?
                    .1,
            )
        } else {
            profile::Profile::Historical(Box::new(pair))
        };
        Ok(GenerationRequestKey {
            request,
            native,
            profile,
            revision,
            build,
            semantic,
        })
    }
}

#[cfg(not(target_arch = "wasm32"))]
impl<B> GenerationRequestKey<B> {
    pub(crate) fn promote_profile(
        mut self,
        force: bool,
        store: &crate::store::Store,
    ) -> Result<Self, crate::node::Error> {
        self.profile = match self.profile {
            profile::Profile::Current(value) => profile::Profile::Current(value),
            profile::Profile::Historical(pair) => profile::Profile::Current(
                pair.promote(force, store)
                    .map_err(|error| match error {
                        crate::profile::Error::Node(error) => *error,
                        error => crate::node::Error::Transform(error.to_string().into()),
                    })?
                    .1,
            ),
        };
        Ok(self)
    }
}

/// `request`'s build request key, with its semantic digest
/// (`generate::semantic_digest`), computed once for both of its keys.
#[cfg(not(target_arch = "wasm32"))]
fn keys<B: crate::surface::Runner>(
    request: &crate::surface::Request<B>,
    native: &crate::input::proof::Proof,
    profile: &crate::profile::Proof,
) -> Result<(BuildRequestKey, [u8; 32]), request::Error> {
    let semantic = generate::semantic_digest(request)?;
    Ok((build_key(request, native, profile, &semantic)?, semantic))
}

#[cfg(all(test, not(target_arch = "wasm32")))]
pub(crate) fn build_request_key<B: crate::surface::Runner>(
    request: &crate::surface::Request<B>,
    native: &crate::input::proof::Proof,
    profile: &crate::profile::Proof,
) -> Result<BuildRequestKey, request::Error> {
    keys(request, native, profile).map(|(build, _)| build)
}

/// `request`'s build request key, with its `semantic` digest.
#[cfg(not(target_arch = "wasm32"))]
fn build_key<B: crate::surface::Runner>(
    request: &crate::surface::Request<B>,
    native: &crate::input::proof::Proof,
    profile: &crate::profile::Proof,
    semantic: &[u8; 32],
) -> Result<BuildRequestKey, request::Error> {
    let mut digest = Sha256::new();
    digest.update(b"rawr.import.build-request/v2");
    digest.update(REQUEST_SCHEMA.to_le_bytes());
    digest.update(GENERATOR_VERSION.to_le_bytes());
    // The sources of the rawr the runner compiles: a runner is generated
    // and built again for another build of rawr, not kept from it, even
    // when its generated files and the Cargo view naming rawr are the same
    // (#1712).
    digest.update(crate::host::DIGEST);
    digest.update(request.contract.as_bytes());
    digest.update(request.fingerprint.as_bytes());
    digest.update(native.native()?.as_bytes());
    digest.update(profile.owner_fingerprint());
    digest.update(semantic);
    let limits = request.allocation.limits();
    digest.update(u64::try_from(limits.0).unwrap_or(u64::MAX).to_le_bytes());
    digest.update(u64::try_from(limits.1).unwrap_or(u64::MAX).to_le_bytes());
    Ok(BuildRequestKey(digest.finalize().into()))
}

/// What rendering a runner's sources reads: the build request's parts but
/// the native build, of which rendering reads only the harness's manifest
/// and lock and the path packages a runner may name. A native edit that
/// leaves them as they were, as a private field's does, renders the same
/// sources, which the overlay this keys keeps (#1821). `semantic` is the
/// request's semantic digest, which the build request key holds too.
#[cfg(not(target_arch = "wasm32"))]
pub(crate) fn rendering_key<B: crate::surface::Runner>(
    request: &crate::surface::Request<B>,
    native: &crate::input::proof::Proof,
    profile: &crate::profile::Proof,
    semantic: &[u8; 32],
) -> [u8; 32] {
    let mut digest = Sha256::new();
    digest.update(b"rawr.import.rendering/v1");
    digest.update(REQUEST_SCHEMA.to_le_bytes());
    digest.update(GENERATOR_VERSION.to_le_bytes());
    digest.update(crate::host::DIGEST);
    digest.update(request.contract.as_bytes());
    digest.update(request.fingerprint.as_bytes());
    digest.update(native.runner_harness_digest());
    for (package, directory) in native.runner_path_packages() {
        for text in [package, directory] {
            digest.update(u64::try_from(text.len()).unwrap_or(u64::MAX).to_le_bytes());
            digest.update(text.as_bytes());
        }
    }
    digest.update(profile.owner_fingerprint());
    digest.update(semantic);
    digest.update([u8::from(crate::universe::enabled())]);
    let limits = request.allocation.limits();
    digest.update(u64::try_from(limits.0).unwrap_or(u64::MAX).to_le_bytes());
    digest.update(u64::try_from(limits.1).unwrap_or(u64::MAX).to_le_bytes());
    digest.finalize().into()
}

#[cfg(not(target_arch = "wasm32"))]
impl<B> GenerationRequestKey<B> {
    /// Borrow the exact cache lookup identity without generating owned files.
    #[must_use]
    pub const fn build_request_key(&self) -> BuildRequestKey {
        self.build
    }

    /// Return only the bounded filesystem observation identities already
    /// retained by this request's exact native-input proof.
    pub fn watch(&self) -> impl Iterator<Item = crate::input::proof::Watch> + '_ {
        self.native.watch()
    }

    pub(crate) const fn snapshot(&self) -> crate::surface::Snapshot {
        self.request.snapshot
    }

    pub(crate) const fn surface_fingerprint(&self) -> crate::surface::Fingerprint {
        self.request.fingerprint
    }

    pub(crate) fn canonical_bytes(&self) -> &[u8] {
        &self.request.canonical
    }

    pub(crate) const fn revision(&self) -> crate::supervisor::Revision {
        self.revision
    }

    /// The request's semantic digest, which its keys share.
    pub(crate) const fn semantic(&self) -> &[u8; 32] {
        &self.semantic
    }

    pub(crate) const fn application_semantic(&self) -> &[u8; 32] {
        self.profile.value().application_semantic()
    }

    /// What a project keeps of this request once its runner is built, for
    /// a later request to take the runner's demand while the runner covers
    /// its own ([`GenerationRequestKey::keeping`], #1743).
    ///
    /// # Errors
    ///
    /// The demand can't be encoded.
    pub fn kept(&self) -> Result<Vec<u8>, crate::surface::Error> {
        crate::surface::Kept::encode(&self.request, &self.build)
    }

    /// This request with the demand of the runner `kept` names, when that
    /// runner covers this request's native items and the widened request
    /// needs it, which holds that its native inputs, contract and profile
    /// are this request's (D936); this request otherwise.
    #[must_use]
    pub fn keeping(mut self, kept: &crate::surface::Kept) -> Self
    where
        B: crate::surface::Runner,
    {
        let native = &self.native;
        let profile = self.profile.value();
        let own = self.request.fingerprint;
        // The widened request's keys, computed once for the widening and
        // for the request it gives.
        let mut widened = None;
        self.request = kept.widen(self.request, |request| {
            let (build, semantic) = keys(request, native, profile).ok()?;
            widened = Some((build, semantic));
            Some(build)
        });
        if self.request.fingerprint != own
            && let Some((build, semantic)) = widened
        {
            self.build = build;
            self.semantic = semantic;
        }
        self
    }

    /// Why the runner this request needs is not `built`, in one line, as
    /// `rawr run` says why it restarts; `None` when it is. Each part of
    /// [`build_request_key`] is named in its order: a native input, the
    /// crates' API, then the native items the program uses. A native input
    /// is never one under `outputs`, the directories builds write.
    pub(crate) fn change_from<P>(
        &self,
        built: &crate::runner::Manifest<P, B>,
        outputs: &[std::path::PathBuf],
    ) -> Option<String> {
        if self.build == built.generated.build_request_key() {
            return None;
        }
        let native = |proof: &crate::input::proof::Proof| {
            proof.native().ok().map(|inputs| *inputs.as_bytes())
        };
        if native(&self.native) != native(&built.native) {
            return Some(
                self.native
                    .change_from(&built.native, outputs)
                    .unwrap_or_else(|| "a native input changed".to_owned()),
            );
        }
        if self.request.contract != built.request.contract {
            return Some("the API of a crate the program uses changed".to_owned());
        }
        // Only a restart asks, so a scan of each plan list is cheap enough.
        let (now, before) = (&self.request.plans, &built.request.plans);
        let missing = |plans: &[crate::surface::adapter::Plan],
                       plan: &crate::surface::adapter::Plan| {
            plans
                .iter()
                .all(|other| other.identity() != plan.identity())
        };
        if let Some(plan) = now.iter().find(|plan| missing(before, plan)) {
            return Some(format!(
                "the program now uses `{}`",
                generate::facade_item_path(plan)
            ));
        }
        if let Some(plan) = before.iter().find(|plan| missing(now, plan)) {
            return Some(format!(
                "the program no longer uses `{}`",
                generate::facade_item_path(plan)
            ));
        }
        Some("the native build's settings changed".to_owned())
    }

    /// Materialize normalized runner files once and seal their manifest.
    pub fn generate(
        self,
    ) -> Result<crate::runner::Manifest<crate::runner::Generated, B>, request::Error>
    where
        B: crate::surface::Runner,
    {
        // A launch is building its runner from here, a build hit included.
        crate::progress::stage(3);
        let began = std::time::Instant::now();
        let generated = if matches!(&self.profile, profile::Profile::Historical(_)) {
            generate::cached::materialize_historical(self)
        } else if self.profile.node_chain().is_some() {
            generate::cached::materialize(self)
        } else {
            crate::metrics::executed(crate::metrics::NodeKind::Overlay, || {
                generate::materialize(self)
            })
        };
        crate::progress::runner_generated(
            began.elapsed(),
            generated
                .as_ref()
                .map_or(0, |manifest| manifest.files.len()),
        );
        generated
    }
}

