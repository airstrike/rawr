//! What a crate's native code uses of its marked modules (D935.3), found
//! from rustc's resolution and type check of every native item: each path
//! that resolves into a marked module, each marked type an expression,
//! pattern or signature has, each member looked up on one, each name a
//! scope that glob-imports a marked module resolved, and each trait native
//! code holds objects of.
//!
//! A marked module is one whose file the shadow crate generated: it starts
//! with [`HEADER`]. Native code is every other item but the island's
//! support module, whose table names the marked modules' generated makers
//! and entries on the runner's behalf.

use std::collections::{BTreeSet, HashMap};

use rustc_hir::def::{DefKind, Res};
use rustc_hir::intravisit::{self, Visitor};
use rustc_hir::{HirId, ItemKind, UseKind};
use rustc_middle::hir::nested_filter;
use rustc_middle::ty::{self, Ty, TyCtxt};
use rustc_span::def_id::{DefId, LocalDefId};
use rustc_span::{FileName, Span, Symbol};

use crate::uses;

/// How every file the shadow crate generates in place of a marked one
/// starts (`island::shadow`).
const HEADER: &str = "// Generated by Rawr from `";

/// The island's support module at the crate root.
const SUPPORT: &str = "__rawr_island";

/// The uses the crate's native code makes of its marked modules.
pub(super) fn uses(tcx: TyCtxt<'_>) -> uses::Uses {
    let mut walk = Walk {
        tcx,
        files: HashMap::new(),
        recorder: uses::Recorder::default(),
        results: None,
        names: HashMap::new(),
        globs: Vec::new(),
    };
    let items = tcx.hir_crate_items(());
    for owner in items.owners() {
        let def_id = owner.def_id;
        if walk.marked(def_id.to_def_id()) || walk.support(def_id.to_def_id()) {
            continue;
        }
        match tcx.hir_owner_node(owner) {
            rustc_hir::OwnerNode::Item(item) => {
                walk.glob(item);
                intravisit::walk_item(&mut walk, item);
            }
            rustc_hir::OwnerNode::ImplItem(item) => intravisit::walk_impl_item(&mut walk, item),
            rustc_hir::OwnerNode::TraitItem(item) => intravisit::walk_trait_item(&mut walk, item),
            rustc_hir::OwnerNode::ForeignItem(item) => {
                intravisit::walk_foreign_item(&mut walk, item);
            }
            _ => {}
        }
    }
    walk.finish()
}

struct Walk<'tcx> {
    tcx: TyCtxt<'tcx>,
    /// Whether each source file is one the shadow crate generated.
    files: HashMap<FileName, bool>,
    recorder: uses::Recorder,
    /// The type check of the body being read.
    results: Option<&'tcx ty::TypeckResults<'tcx>>,
    /// The first segment of each path native code wrote, by the module
    /// it wrote it in.
    names: HashMap<LocalDefId, BTreeSet<Symbol>>,
    /// Each native module that glob-imports a marked one, with that
    /// module's path.
    globs: Vec<(LocalDefId, String)>,
}

impl<'tcx> Walk<'tcx> {
    /// Each name a globbing module resolved, as its glob's module's.
    fn finish(mut self) -> uses::Uses {
        for (module, globbed) in std::mem::take(&mut self.globs) {
            for name in self.names.get(&module).into_iter().flatten() {
                self.recorder.scope(&globbed, name.as_str());
            }
        }
        self.recorder.finish()
    }

    /// Whether `def_id` is declared in a file the shadow crate generated:
    /// a module by its contents, which a file module's `mod` item in its
    /// parent's file doesn't show.
    fn marked(&mut self, def_id: DefId) -> bool {
        let tcx = self.tcx;
        if tcx.def_kind(def_id) == DefKind::Mod {
            if let Some(local) = def_id.as_local() {
                let (module, ..) =
                    tcx.hir_get_module(rustc_span::def_id::LocalModDefId::new_unchecked(local));
                return self.generated(module.spans.inner_span);
            }
            let children = tcx.module_children(def_id);
            return children.iter().any(|child| {
                child.reexport_chain.is_empty()
                    && child
                        .res
                        .opt_def_id()
                        .is_some_and(|child| self.marked(child))
            });
        }
        let span = tcx.def_span(def_id);
        self.generated(span)
    }

    fn generated(&mut self, span: Span) -> bool {
        let file = self.tcx.sess.source_map().lookup_source_file(span.lo());
        if let Some(&generated) = self.files.get(&file.name) {
            return generated;
        }
        let generated = match file.src.as_deref() {
            Some(text) => text.starts_with(HEADER),
            // A dependency's file, as the binary's crate reads its library's
            // marked modules: read from where it is.
            None => match &file.name {
                FileName::Real(real) => real
                    .local_path()
                    .and_then(|path| std::fs::read(path).ok())
                    .is_some_and(|bytes| bytes.starts_with(HEADER.as_bytes())),
                _ => false,
            },
        };
        self.files.insert(file.name.clone(), generated);
        generated
    }

    /// Whether `def_id` is the island's support module or inside it.
    fn support(&self, def_id: DefId) -> bool {
        self.tcx
            .def_path(def_id)
            .data
            .first()
            .and_then(|data| data.data.get_opt_name())
            .is_some_and(|name| name.as_str() == SUPPORT)
    }

    /// The path a marked item's shape names it by, from the crate root:
    /// `physics::Counter`, an inherent member as `physics::Counter::new`.
    /// `None` for what has no such path, as a trait impl's member.
    fn path(&self, def_id: DefId) -> Option<String> {
        let tcx = self.tcx;
        match tcx.def_kind(def_id) {
            DefKind::Ctor(..) | DefKind::Field => return self.path(tcx.parent(def_id)),
            DefKind::AssocFn | DefKind::AssocConst { .. } | DefKind::AssocTy => {
                let parent = tcx.parent(def_id);
                if let DefKind::Impl { of_trait } = tcx.def_kind(parent) {
                    if of_trait {
                        return None;
                    }
                    let ty::Adt(adt, _) = tcx
                        .type_of(parent)
                        .instantiate_identity()
                        .skip_norm_wip()
                        .kind()
                    else {
                        return None;
                    };
                    let owner = self.path(adt.did())?;
                    return Some(format!("{owner}::{}", tcx.item_name(def_id)));
                }
            }
            _ => {}
        }
        let mut segments = Vec::new();
        for data in tcx.def_path(def_id).data {
            segments.push(data.data.get_opt_name()?.to_string());
        }
        Some(segments.join("::"))
    }

    /// A resolution native code made: a trait of any crate, and a marked
    /// item it names.
    fn resolved(&mut self, res: Res) {
        let Res::Def(kind, def_id) = res else {
            return;
        };
        let tcx = self.tcx;
        match kind {
            DefKind::Trait | DefKind::TraitAlias => {
                self.recorder.trait_(tcx.item_name(def_id).to_string());
            }
            DefKind::AssocFn | DefKind::AssocConst { .. } | DefKind::AssocTy
                if matches!(tcx.def_kind(tcx.parent(def_id)), DefKind::Trait) =>
            {
                let parent = tcx.parent(def_id);
                self.recorder.trait_(tcx.item_name(parent).to_string());
                if self.marked(parent) {
                    self.name(parent);
                }
            }
            _ => {}
        }
        if !self.marked(def_id) {
            return;
        }
        match kind {
            DefKind::Ctor(..) | DefKind::Variant | DefKind::Field => {
                let owner = match kind {
                    DefKind::Ctor(rustc_hir::def::CtorOf::Variant, _) => {
                        tcx.parent(tcx.parent(def_id))
                    }
                    _ => tcx.parent(def_id),
                };
                self.adt(owner);
            }
            DefKind::Struct | DefKind::Enum | DefKind::Union => self.adt(def_id),
            DefKind::TyAlias => {
                self.name(def_id);
                self.ty(tcx.type_of(def_id).instantiate_identity().skip_norm_wip());
            }
            DefKind::Fn | DefKind::AssocFn => {
                self.name(def_id);
                self.signature(def_id);
            }
            DefKind::Const { .. } | DefKind::AssocConst { .. } | DefKind::Static { .. } => {
                self.name(def_id);
                self.ty(tcx.type_of(def_id).instantiate_identity().skip_norm_wip());
            }
            _ => self.name(def_id),
        }
    }

    fn name(&mut self, def_id: DefId) {
        if let Some(path) = self.path(def_id) {
            self.recorder.name(path);
        }
    }

    /// Native code is built against the marked type `def_id`: named, and
    /// held, with every marked type its fields reach.
    fn adt(&mut self, def_id: DefId) {
        let Some(path) = self.path(def_id) else {
            return;
        };
        self.recorder.name(path.clone());
        if !self.recorder.hold(path) {
            return;
        }
        let tcx = self.tcx;
        for field in tcx.adt_def(def_id).all_fields() {
            self.ty(tcx
                .type_of(field.did)
                .instantiate_identity()
                .skip_norm_wip());
        }
    }

    /// Each marked type a named function's signature reaches.
    fn signature(&mut self, def_id: DefId) {
        let signature = self
            .tcx
            .fn_sig(def_id)
            .instantiate_identity()
            .skip_norm_wip();
        for ty in signature.skip_binder().inputs_and_output {
            self.ty(ty);
        }
    }

    /// Each marked type `ty` reaches, and each trait object it holds.
    fn ty(&mut self, ty: Ty<'tcx>) {
        for part in ty.walk() {
            let ty::GenericArgKind::Type(inner) = part.kind() else {
                continue;
            };
            match inner.kind() {
                ty::Adt(adt, _) if self.marked(adt.did()) => self.adt(adt.did()),
                ty::Dynamic(predicates, ..) => {
                    if let Some(principal) = predicates.principal_def_id() {
                        let name = self.tcx.item_name(principal).to_string();
                        self.recorder.object(name.clone());
                        self.recorder.trait_(name);
                        if self.marked(principal) {
                            self.name(principal);
                        }
                    }
                }
                ty::FnDef(def_id, _) if self.marked(*def_id) => {
                    self.name(*def_id);
                    self.signature(*def_id);
                }
                _ => {}
            }
        }
    }

    /// `member` looked up on each marked type `ty` reaches.
    fn probe(&mut self, ty: Ty<'tcx>, member: Symbol) {
        for part in ty.walk() {
            if let ty::GenericArgKind::Type(inner) = part.kind()
                && let ty::Adt(adt, _) = inner.kind()
                && self.marked(adt.did())
                && let Some(owner) = self.path(adt.did())
            {
                self.recorder.probe(&owner, member.as_str());
            }
        }
    }

    /// A native `use module::*;` of a marked module.
    fn glob(&mut self, item: &'tcx rustc_hir::Item<'tcx>) {
        let ItemKind::Use(path, UseKind::Glob) = item.kind else {
            return;
        };
        for res in path.res.present_items() {
            if let Res::Def(DefKind::Mod | DefKind::Enum, def_id) = res
                && self.marked(def_id)
                && let Some(module) = self.path(def_id)
            {
                let scope = self.tcx.parent_module_from_def_id(item.owner_id.def_id);
                self.globs.push((scope.to_local_def_id(), module));
            }
        }
    }
}

impl<'tcx> Visitor<'tcx> for Walk<'tcx> {
    type NestedFilter = nested_filter::OnlyBodies;

    fn maybe_tcx(&mut self) -> TyCtxt<'tcx> {
        self.tcx
    }

    fn visit_nested_body(&mut self, id: rustc_hir::BodyId) {
        let outer = self.results.replace(self.tcx.typeck_body(id));
        self.visit_body(self.tcx.hir_body(id));
        self.results = outer;
    }

    fn visit_path(&mut self, path: &rustc_hir::Path<'tcx>, id: HirId) {
        self.resolved(path.res);
        if let Some(first) = path.segments.first()
            && !matches!(path.res, Res::Local(_))
        {
            let module = self.tcx.parent_module(id).to_local_def_id();
            self.names
                .entry(module)
                .or_default()
                .insert(first.ident.name);
        }
        intravisit::walk_path(self, path);
    }

    fn visit_use(&mut self, path: &'tcx rustc_hir::UsePath<'tcx>, id: HirId) {
        for res in path.res.present_items() {
            self.resolved(res);
        }
        intravisit::walk_use(self, path, id);
    }

    fn visit_qpath(&mut self, qpath: &'tcx rustc_hir::QPath<'tcx>, id: HirId, _span: Span) {
        if let rustc_hir::QPath::TypeRelative(qself, segment) = qpath
            && let rustc_hir::TyKind::Path(rustc_hir::QPath::Resolved(None, path)) = qself.kind
            && let Res::Def(
                DefKind::Struct | DefKind::Enum | DefKind::Union | DefKind::TyAlias,
                def_id,
            ) = path.res
        {
            let ty = self
                .tcx
                .type_of(def_id)
                .instantiate_identity()
                .skip_norm_wip();
            self.probe(ty, segment.ident.name);
        }
        intravisit::walk_qpath(self, qpath, id);
    }

    fn visit_expr(&mut self, expr: &'tcx rustc_hir::Expr<'tcx>) {
        if let Some(results) = self.results {
            if let Some(ty) = results.node_type_opt(expr.hir_id) {
                self.ty(ty);
            }
            if let Some(ty) = results.expr_ty_adjusted_opt(expr) {
                self.ty(ty);
            }
            if let Some(def_id) = results.type_dependent_def_id(expr.hir_id) {
                self.resolved(Res::Def(self.tcx.def_kind(def_id), def_id));
            }
            if let rustc_hir::ExprKind::MethodCall(segment, receiver, ..) = expr.kind
                && let Some(ty) = results.node_type_opt(receiver.hir_id)
            {
                self.probe(ty, segment.ident.name);
            }
        }
        intravisit::walk_expr(self, expr);
    }

    fn visit_pat(&mut self, pat: &'tcx rustc_hir::Pat<'tcx>) {
        if let Some(ty) = self
            .results
            .and_then(|results| results.node_type_opt(pat.hir_id))
        {
            self.ty(ty);
        }
        intravisit::walk_pat(self, pat);
    }
}
