//! What the suite's tests share: the process's native Cargo lane, one Cargo
//! build directory, and the builds of generated crates.
//!
//! The lane admits one owner per process and refuses a second outright, so a
//! test holds [`lane`] around each call that takes it (resolution,
//! extraction, a runner build, `cargo::Owner::acquire`) and nothing else.
//! A test never holds the lane while it asks for a shared fixture: the
//! fixture takes the lane itself the first time it is built.

#![cfg_attr(not(feature = "test-fixtures"), allow(unused_imports))]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::{MutexGuard, OnceLock};

/// This test's turn on the process's native Cargo lane.
pub fn lane() -> MutexGuard<'static, ()> {
    rawr_import::store::test_turn()
}

/// The Cargo build directory every runner and generated-crate build in the
/// suite shares, beside the test store in the workspace's `target`.
///
/// Cargo keys each unit in it as `cargo build` does (package, source,
/// features, profile and toolchain) and decides what is fresh, so `rawr` and
/// its dependencies compile once per configuration and stay compiled across
/// runs until their sources, the lockfile or the toolchain change. Only
/// builds under the default Cargo home share it: Cargo rebuilds a unit whose
/// registry sources it finds under another home's path.
#[cfg(feature = "test-fixtures")]
pub fn build_directory() -> &'static Path {
    static DIRECTORY: OnceLock<PathBuf> = OnceLock::new();
    DIRECTORY.get_or_init(|| {
        require_project_targets();
        let directory = rawr_import::store::isolate_for_tests()
            .parent()
            .expect("the test store has a parent")
            .join("build");
        fs::create_dir_all(&directory).expect("the shared build directory is created");
        rawr_import::runner::share_build_directory(directory.clone());
        directory
    })
}

/// Rawr puts a project's runner cache and store in `<target>/rawr`,
/// `CARGO_TARGET_DIR` first, as Cargo does. Inherited from the caller, it
/// would give every test project one cache and one store, so the suite runs
/// with `--target-dir` instead.
pub fn require_project_targets() {
    assert!(
        std::env::var_os("CARGO_TARGET_DIR").is_none(),
        "run this suite with `--target-dir`, not `CARGO_TARGET_DIR`: each test project keeps \
         its own `target/rawr`"
    );
}

/// `manifest`'s generated crate, written into a fresh project.
#[cfg(feature = "test-fixtures")]
pub fn generated_crate(
    manifest: &rawr_import::runner::Manifest<rawr_import::runner::Generated, ()>,
    label: &str,
) -> rawr_import::store::TestProject {
    let project = rawr_import::store::TestProject::new(label);
    let root = project.path();
    for file in manifest.files() {
        let path = root.join(file.path());
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).expect("the generated file's parent is created");
        }
        fs::write(path, file.bytes()).expect("the exact generated bytes are written");
    }
    fs::write(
        root.join("rawr-generated-manifest.carrier"),
        manifest
            .generated_manifest()
            .carrier()
            .expect("the derived carrier encodes"),
    )
    .expect("the derived carrier is written beside the keyed files");
    project
}

/// Run `cargo <arguments>` on the generated crate at `project` in the shared
/// build directory, its final artifacts in the project's own target
/// directory.
#[cfg(feature = "test-fixtures")]
pub fn cargo_on(project: &rawr_import::store::TestProject, arguments: &[&str]) -> Output {
    let root = project.path();
    let build = toml_string(build_directory());
    Command::new(cargo())
        .args(arguments)
        .args(["--offline", "--locked", "--config"])
        .arg(format!("build.build-dir={build}"))
        .arg("--manifest-path")
        .arg(root.join("Cargo.toml"))
        .env("CARGO_TARGET_DIR", root.join("target"))
        .output()
        .expect("Cargo launches on the generated crate")
}

/// Panic with Cargo's output unless it succeeded.
#[cfg(feature = "test-fixtures")]
pub fn assert_success(output: &Output, what: &str) {
    assert!(
        output.status.success(),
        "{what} failed:\n{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

#[cfg(feature = "test-fixtures")]
fn toml_string(path: &Path) -> String {
    let text = path
        .to_str()
        .expect("the shared build directory is Unicode");
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

#[cfg(feature = "test-fixtures")]
fn cargo() -> PathBuf {
    std::env::var_os("CARGO")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("cargo"))
}
