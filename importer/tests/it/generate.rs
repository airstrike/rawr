use crate::p3;

use std::fs;
use std::path::PathBuf;
use std::process::Command;
use std::sync::atomic::{AtomicU64, Ordering};

static TEST_ID: AtomicU64 = AtomicU64::new(1);

#[test]
fn exact_operation_forms_emit_rooted_normalized_thunks() {
    let _turn = rawr_import::store::test_turn();
    let manifest = p3::generated();
    let main = manifest
        .files()
        .find(|file| file.path() == "src/main.rs")
        .expect("the generated runner has one source root");
    let main = std::str::from_utf8(main.bytes()).expect("generated Rust is UTF-8");
    assert!(main.contains("static ADAPTER_MODULES: &[&[Adapter]]"));
    assert!(
        !main.contains("fn adapter_"),
        "adapters live in their modules"
    );
    let source = manifest
        .files()
        .filter(|file| file.path().starts_with("src/"))
        .map(|file| std::str::from_utf8(file.bytes()).expect("generated Rust is UTF-8"))
        .collect::<String>();
    let source = source.as_str();

    assert!(source.contains("pub(super) static ADAPTERS: &[Adapter]"));
    assert!(source.contains("use super::*;"));
    assert!(source.contains("facade_a::Record::new("));
    assert!(source.contains("let receiver: facade_a::Record = take_native"));
    assert!(source.contains("arena.shared::<facade_a::Record, _>"));
    assert!(source.contains("arena.mutable::<facade_a::Record, _>"));
    assert!(source.contains("receiver.owned("));
    assert!(source.contains("facade_a::Forms::Tuple("));
    assert!(source.contains("struct Arena"));
    assert!(!source.contains("Arc<"));
    assert!(!source.contains("Mutex<"));
    assert!(!source.as_bytes().contains(&b'\r'));
}

#[test]
fn generated_standalone_crate_typechecks_the_rooted_table() {
    let _turn = rawr_import::store::test_turn();
    let manifest = p3::generated();
    let root = std::env::temp_dir().join(format!(
        "rawr-generated-crate-{}-{}",
        std::process::id(),
        TEST_ID.fetch_add(1, Ordering::Relaxed)
    ));
    fs::create_dir_all(root.join("src")).expect("the generated crate directory exists");
    for file in manifest.files() {
        let path = root.join(file.path());
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).expect("the generated file parent exists");
        }
        fs::write(path, file.bytes()).expect("the exact generated bytes are written");
    }
    fs::write(
        root.join("rawr-generated-manifest.carrier"),
        manifest
            .generated_manifest()
            .carrier()
            .expect("the derived carrier encodes"),
    )
    .expect("the derived carrier is written separately from keyed files");
    let output = Command::new(cargo())
        .args(["check", "--offline", "--locked", "-j1", "--manifest-path"])
        .arg(root.join("Cargo.toml"))
        .env("CARGO_TARGET_DIR", root.join("target"))
        .output()
        .expect("the generated Cargo check launches");
    let _ = fs::remove_dir_all(&root);
    assert!(
        output.status.success(),
        "generated crate failed to typecheck:\n{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn cargo() -> PathBuf {
    std::env::var_os("CARGO")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("cargo"))
}

/// The runner source is `src/main.rs` plus one module per imported crate
/// and identity bucket. Generation is deterministic, and dropping one adapter
/// changes exactly one module file, so syncing the second generation over the
/// first rewrites only that file; every other file keeps its mtime.
#[test]
fn one_adapter_change_rewrites_only_its_module_file() {
    let _turn = rawr_import::store::test_turn();
    let project = rawr_import::store::TestProject::new("rawr-p3-modules");
    let limits = rawr_import::cargo::Limits::standard();
    let sources = |surface: p3::Surface| {
        p3::request_at(project.path(), b"exact p3 surface", surface)
            .0
            .generate(&limits)
            .expect("the generated manifest seals")
            .files()
            .map(|file| (file.path().to_owned(), file.bytes().to_vec()))
            .collect::<Vec<_>>()
    };
    let before = sources(p3::Surface::Complete);
    assert_eq!(
        before,
        sources(p3::Surface::Complete),
        "same inputs, same bytes"
    );
    let modules = before
        .iter()
        .filter(|(path, _)| path.starts_with("src/rawr_adapters_"))
        .count();
    assert!(modules > 1, "adapters split into modules");

    // The first outcome whose removal leaves its module in place.
    let (after, module) = (0..32)
        .find_map(|skip| {
            let after = sources(p3::Surface::Without(skip));
            let changed = before
                .iter()
                .zip(&after)
                .filter(|(left, right)| left != right)
                .map(|(left, _)| left.0.clone())
                .collect::<Vec<_>>();
            // A demand change also restamps `src/rawr_surface.rs`;
            // `src/main.rs` and every other module stay byte-identical.
            match changed.as_slice() {
                [module, stamps]
                    if after.len() == before.len()
                        && module.starts_with("src/rawr_adapters_")
                        && stamps == "src/rawr_surface.rs" =>
                {
                    Some((after, module.clone()))
                }
                _ => None,
            }
        })
        .expect("one adapter's removal changes exactly one adapter module");

    let work = project.path().join("work");
    let sync = |files: &[(String, Vec<u8>)]| {
        rawr_import::bridge::sync_sources(
            &work,
            files
                .iter()
                .map(|(path, bytes)| (path.as_str(), bytes.as_slice())),
        )
        .expect("the sources sync")
    };
    assert_eq!(sync(&before).len(), before.len());
    let modified = |path: &str| {
        fs::metadata(work.join(path))
            .and_then(|metadata| metadata.modified())
            .expect("a synced file")
    };
    let stamps = before
        .iter()
        .map(|(path, _)| modified(path))
        .collect::<Vec<_>>();
    std::thread::sleep(std::time::Duration::from_millis(20));
    let surface = "src/rawr_surface.rs";
    assert_eq!(
        sync(&after),
        [PathBuf::from(&module), PathBuf::from(surface)]
    );
    for ((path, _), stamp) in before.iter().zip(stamps) {
        assert_eq!(
            modified(path) != stamp,
            *path == module || path == surface,
            "{path}"
        );
    }
}
