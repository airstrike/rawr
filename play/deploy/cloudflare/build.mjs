// Builds the site (site/, an Astro package: `npm run build` writes
// site/dist) and merges its pages with the bot's files (public/) into dist/,
// the one assets directory the Worker serves. Wrangler runs it before every
// deploy and dev (`build` in wrangler.jsonc). A path in both fails, and so
// does a file over Cloudflare's 25 MiB limit on an asset (limits.mjs).
// It also writes src/cards.gen.ts, each link card's URL with its content
// hash (below), and src/site.gen.ts, the site's frame as its built pages
// have it: the stylesheets every page loads, the site bar and the footer. The bot's pages
// take it (src/look.ts): the status page the Worker draws, and /bot/invite,
// whose marked places it fills in here.
//   node build.mjs              build the site, then merge
//   SITE_BUILT=1 node build.mjs merge the site's existing dist/
// The site needs its packages: `npm ci` in site/ once.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { ASSET_LIMIT, mib, oversized } from "./limits.mjs";

const here = import.meta.dirname;
const site = join(here, "../../../site");
const sources = [join(site, "dist"), join(here, "public")];
const dist = join(here, "dist");

if (!process.env.SITE_BUILT) {
  if (!existsSync(join(site, "node_modules"))) {
    console.error("build: the site's packages are not installed; run `npm ci` in site/");
    process.exit(1);
  }
  const built = spawnSync("npm", ["run", "build"], { cwd: site, stdio: "inherit" });
  if (built.status !== 0) {
    console.error("build: the site's build failed");
    process.exit(1);
  }
}
if (!existsSync(join(sources[0], "play.html"))) {
  console.error("build: site/dist has no play.html; build the site first");
  process.exit(1);
}

function files(dir) {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(dir, join(entry.parentPath, entry.name)));
}

const seen = new Map();
for (const source of sources) {
  for (const file of files(source)) {
    if (seen.has(file)) {
      console.error(`build: ${file} is in both ${seen.get(file)} and ${source}`);
      process.exit(1);
    }
    seen.set(file, source);
  }
}
// The Worker serves /web from R2 (src/web.ts) before the assets, so a module
// among them would ship and never be served.
const modules = [...seen.keys()].filter((file) => file.startsWith("web/"));
if (modules.length > 0) {
  console.error(`build: rawr-web's files come from R2, not the assets; remove ${modules.map((file) => join(seen.get(file), file)).join(", ")}`);
  process.exit(1);
}

// The site's frame, from its built pages: the stylesheets both the landing
// page and the playground load (global.css compiled: the tokens, the reset,
// the bar and the footer; and the theme switch's), then the landing page's
// bar, the script that shades it once the page scrolls, and its footer. The
// bot's pages link the same files, so their look can't drift from the site's.
const read = (name) => readFileSync(join(sources[0], name), "utf8");
const sheets = (html) => [...html.matchAll(/<link rel="stylesheet" href="(\/_astro\/[^"]+\.css)">/g)].map((m) => m[1]);
const landing = read("index.html");
const shared = sheets(landing).filter((href) => sheets(read("play.html")).includes(href));
if (shared.length === 0) {
  console.error("build: the landing page and the playground share no stylesheet");
  process.exit(1);
}
const piece = (name, pattern) => {
  const found = landing.match(pattern);
  if (!found) {
    console.error(`build: site/dist/index.html has no ${name}`);
    process.exit(1);
  }
  return found[0];
};
const frame = {
  STYLES: shared,
  BAR: piece("site bar", /<div class="bar-top"[^>]*><\/div>\s*<header class="bar">[\s\S]*?<\/header>/),
  BAR_SCRIPT: piece("bar script", /<script>(?:(?!<\/script>)[\s\S])*\.bar-top(?:(?!<\/script>)[\s\S])*<\/script>/),
  FOOTER: piece("footer", /<footer class="site">[\s\S]*?<\/footer>/),
};
writeFileSync(
  join(here, "src/site.gen.ts"),
  `// Generated by build.mjs from the site's built pages. Do not edit.\n${Object.entries(frame)
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`)
    .join("")}`,
);

rmSync(dist, { recursive: true, force: true });
for (const source of sources) cpSync(source, dist, { recursive: true });
console.log(`build: ${seen.size} files in dist/`);

const large = oversized(dist);
if (large.length > 0) {
  console.error(`build: Cloudflare takes no asset over ${mib(ASSET_LIMIT)}:`);
  for (const [file, size] of large) console.error(`  ${file}: ${mib(size)} (${size} bytes)`);
  process.exit(1);
}

// The bot's static page in the site's look.
const look = await import("./src/look.ts");
const marks = {
  "<!-- build.mjs: the site's head (look.ts's HEAD and BASE) -->": `${look.HEAD}\n<style>${look.BASE}</style>`,
  "<!-- build.mjs: the site bar -->": look.BAR,
  "<!-- build.mjs: the site's footer -->": look.FOOTER,
};
const invite = join(dist, "bot/invite/index.html");
let invitePage = readFileSync(invite, "utf8");
for (const [mark, text] of Object.entries(marks)) {
  if (!invitePage.includes(mark)) {
    console.error(`build: bot/invite/index.html has no "${mark}"`);
    process.exit(1);
  }
  invitePage = invitePage.replace(mark, () => text);
}
writeFileSync(invite, invitePage);

// Link previews (Discord, Slack, iMessage) cache a card by its URL, so the
// pages name each card with its content hash: a new card is a new URL. The
// Worker's own pages (/play and its shares) take the same URLs from
// src/cards.gen.ts.
const cards = Object.fromEntries(
  files(join(dist, "og"))
    .filter((name) => name.endsWith(".png"))
    .sort()
    .map((name) => {
      const card = `og/${name}`;
      const version = createHash("sha256").update(readFileSync(join(dist, card))).digest("hex").slice(0, 12);
      return [card, `${card}?v=${version}`];
    }),
);
for (const file of files(dist).filter((file) => file.endsWith(".html"))) {
  const path = join(dist, file);
  let page = readFileSync(path, "utf8");
  for (const [card, versioned] of Object.entries(cards)) page = page.replaceAll(card, versioned);
  writeFileSync(path, page);
}
writeFileSync(
  join(here, "src/cards.gen.ts"),
  `// Generated by build.mjs: each link card's path with its content hash. Do not edit.\nexport const CARDS: Record<string, string> = ${JSON.stringify(cards, null, 2)};\n`,
);
for (const versioned of Object.values(cards)) console.log(`build: the card ${versioned}`);
