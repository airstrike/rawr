// The sources POST /play/run accepts: the text of every `<code data-run>`
// element in the site's HTML pages (site/public). build.mjs writes their
// SHA-256 hashes to src/runnable.gen.ts, which the Worker imports.
//
// The text is decoded as a browser's `textContent` reads it, since that is
// what the pages' Run buttons send. A block that is empty or holds markup
// fails the build. So do two blocks with the same `data-run` name and
// different text, on one page or on two.
import { readdirSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { runBlocks, sha256 } from "./src/play.ts";

/** Every .html file under `dir`, as a map from its relative path to its text. */
export function sitePages(dir) {
  const pages = new Map();
  for (const entry of readdirSync(dir, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith(".html")) continue;
    const path = join(entry.parentPath, entry.name);
    pages.set(relative(dir, path), readFileSync(path, "utf8"));
  }
  return new Map([...pages].sort(([a], [b]) => a.localeCompare(b)));
}

/**
 * The allow-list for `pages` (path to HTML): the sorted, distinct SHA-256
 * hashes of their run blocks, and the blocks themselves. Throws on an empty
 * block, a block with markup, or two blocks with one name and different text.
 */
export async function allowList(pages) {
  const blocks = [];
  const named = new Map();
  const errors = [];
  for (const [page, html] of pages) {
    for (const block of runBlocks(html)) {
      const where = `${page} (data-run${block.name ? `="${block.name}"` : ""})`;
      if (block.code.trim() === "") errors.push(`${where} is empty`);
      if (/<[A-Za-z\/!]/.test(block.html)) errors.push(`${where} holds markup; a run block must be plain text`);
      if (block.name) {
        const first = named.get(block.name);
        if (!first) named.set(block.name, { page, code: block.code });
        else if (first.code !== block.code) errors.push(`${where} differs from the block of the same name in ${first.page}`);
      }
      blocks.push({ page, name: block.name, code: block.code, hash: await sha256(block.code) });
    }
  }
  if (blocks.length === 0) errors.push("no <code data-run> blocks in the site");
  if (errors.length > 0) throw new Error(`run blocks:\n  ${errors.join("\n  ")}`);
  const hashes = [...new Set(blocks.map((block) => block.hash))].sort();
  return { hashes, blocks };
}

/** The generated module's text. */
export function module(hashes) {
  return [
    "// Generated by build.mjs from the site's <code data-run> blocks. Do not edit.",
    "// The SHA-256 of each source POST /play/run accepts without Turnstile.",
    `export const RUNNABLE: readonly string[] = ${JSON.stringify(hashes, null, 2)};`,
    "",
  ].join("\n");
}
