//! The instances native code calls marked generic functions at (D866,
//! D869), as the last check of the generated crate recorded them
//! (`rawr_import::record`). `rawr check` keeps the record beside the
//! project's other rawr files ([`store`]), where the shadow crate's support
//! table ([`super::island::support`]) and the resolver, which compiles each
//! instance, both read it, so they never disagree. The record names the
//! build of rawr that kept it, and only that build reads it; a check of
//! another build takes it as its first guess ([`adopt`]).

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use rawr_import::record::{Instance, Record};

use super::graph::Graph;

/// One instance the support table holds: the path the generic function's
/// call names, its instance entry's path from the crate root, and its type
/// arguments, written from the crate root.
#[derive(Clone, Debug, Eq, PartialEq)]
pub(crate) struct Entry {
    pub(crate) path: String,
    pub(crate) function: String,
    pub(crate) types: Vec<String>,
}

/// Where the project whose Rawr directory is `rawr` keeps its record.
fn location_in(rawr: &Path) -> PathBuf {
    rawr.join("instances.json")
}

/// The build of rawr that keeps a record: the digest of its sources
/// ([`rawr_import::host::digest`]), in hex. The record came from the shadow
/// crate this build generated, so another build reads it as none and
/// records its own, as a fresh project does (#1601). The runner this build
/// makes names the same digest at its start ([`identify`]), so it reads the
/// record its check kept (#1606).
fn build() -> String {
    rawr_import::host::digest()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// Name the build of rawr a runner was generated by, whose check kept the
/// records the runner reads. The shared runtime a runner links is compiled
/// once for every build whose libraries agree and carries no digest of its
/// own (#1983), so the generated runner names its build here before it runs.
#[doc(hidden)]
pub fn identify(build: [u8; 32]) {
    rawr_import::host::identify(build);
}

/// A kept record's bytes: the build's line, then the record.
fn encode(build: &str, record: &Record) -> io::Result<Vec<u8>> {
    let mut bytes = format!("{build}\n").into_bytes();
    serde_json::to_writer(&mut bytes, record).map_err(io::Error::other)?;
    Ok(bytes)
}

/// The record in `bytes` if `build` kept it, or none.
fn decode(build: &str, bytes: &[u8]) -> Record {
    bytes
        .strip_prefix(build.as_bytes())
        .and_then(|rest| rest.strip_prefix(b"\n"))
        .and_then(|record| serde_json::from_slice(record).ok())
        .unwrap_or_default()
}

/// Keep `record` as the project at `root`'s; whether it differs from the
/// one kept before, so the shadow crate's table must be written again.
///
/// # Errors
///
/// The record can't be written.
pub fn store(root: &Path, record: &Record) -> io::Result<bool> {
    store_in(&rawr_import::location::rawr_directory_here(root), record)
}

/// [`store`] for the project whose Rawr directory is `rawr`.
///
/// # Errors
///
/// The record can't be written.
pub fn store_in(rawr: &Path, record: &Record) -> io::Result<bool> {
    let path = location_in(rawr);
    let bytes = encode(&build(), record)?;
    if fs::read(&path).is_ok_and(|kept| kept == bytes) {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&path, bytes)?;
    Ok(true)
}

/// Take the record another build of rawr kept at `root` as this build's
/// first guess, so a check after an install starts from the instances the
/// last check recorded rather than from none. The guess is checked
/// as any kept record is: the build's identity keys every resolution, so
/// this build resolves again, and a build whose check records other
/// instances stops before its probe and checks again with them (D869). A
/// record of this build, or none, is left as it is.
///
/// # Errors
///
/// The record can't be written.
pub fn adopt(root: &Path) -> io::Result<()> {
    adopt_in(&rawr_import::location::rawr_directory_here(root))
}

/// [`adopt`] for the project whose Rawr directory is `rawr`.
///
/// # Errors
///
/// The record can't be written.
pub fn adopt_in(rawr: &Path) -> io::Result<()> {
    let Ok(bytes) = fs::read(location_in(rawr)) else {
        return Ok(());
    };
    let Some((kept_by, record)) = bytes
        .split_first_chunk::<64>()
        .and_then(|(line, rest)| Some((line, rest.strip_prefix(b"\n")?)))
    else {
        return Ok(());
    };
    if *kept_by == *build().as_bytes() || !kept_by.iter().all(u8::is_ascii_hexdigit) {
        return Ok(());
    }
    // A record of another layout is none, as `Record::read` reads it.
    let layout = serde_json::from_slice::<serde_json::Value>(record)
        .ok()
        .and_then(|record| record.get("schema")?.as_u64());
    if layout != Some(u64::from(rawr_import::record::SCHEMA)) {
        return Ok(());
    }
    match serde_json::from_slice::<Record>(record) {
        Ok(record) => store_in(rawr, &record).map(drop),
        Err(_) => Ok(()),
    }
}

/// The record the project at `root` keeps, or none.
#[must_use]
pub fn kept(root: &Path) -> Record {
    kept_in(&rawr_import::location::rawr_directory_here(root))
}

/// [`kept`] for the project whose Rawr directory is `rawr`.
#[must_use]
pub fn kept_in(rawr: &Path) -> Record {
    fs::read(location_in(rawr))
        .map(|bytes| decode(&build(), &bytes))
        .unwrap_or_default()
}

/// The name rawr gives the instance of a generic function whose types'
/// tuple is named `name`, as `type_name` names it: FNV-1a of the name, as
/// the shadow crate's `keyed` hashes it at run time.
#[must_use]
pub(crate) fn key(name: &str) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in name.bytes() {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
    format!("{hash:016x}")
}

/// A short digest of `text`, as a profile identity names the record it
/// was checked with.
#[must_use]
pub fn digest(text: &str) -> String {
    key(text)
}

impl Graph {
    /// The instances the project's native code calls marked generic
    /// functions at.
    pub(crate) fn native_instances(&self) -> Vec<Instance> {
        kept_in(&self.rawr_directory()).instances().to_vec()
    }

    /// The support table's entries: each recorded instance of a function
    /// the shadow crate has an instance entry for, among `generic`, each
    /// entry's path by its call's.
    pub(crate) fn instance_entries(
        &self,
        generic: &std::collections::BTreeMap<String, String>,
    ) -> Vec<Entry> {
        self.native_instances()
            .into_iter()
            .filter_map(|instance| {
                Some(Entry {
                    function: generic.get(&instance.path)?.clone(),
                    path: instance.path,
                    types: instance.types,
                })
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use rawr_import::record::{Instance, Record};

    #[test]
    fn a_record_another_build_kept_is_read_as_none() {
        let record = Record::new(vec![Instance {
            path: "widget::row_group".into(),
            name: "(app::Message,)".into(),
            types: vec!["crate::Message".into()],
        }]);
        let bytes = super::encode("aa", &record).expect("the record encodes");
        assert_eq!(super::decode("aa", &bytes), record);
        assert_eq!(super::decode("ab", &bytes), Record::default());
        assert_eq!(super::decode("a", &bytes), Record::default());
        // A record kept before records named their build is another's.
        let unnamed = serde_json::to_vec(&record).expect("the record encodes");
        assert_eq!(super::decode("aa", &unnamed), Record::default());
    }

    #[test]
    fn a_record_another_build_kept_is_adopted_as_this_builds() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("target/tmp")
            .join(format!("instances-adopt-{}", std::process::id()));
        let record = Record::new(vec![Instance {
            path: "widget::row_group".into(),
            name: "(app::Message,)".into(),
            types: vec!["crate::Message".into()],
        }]);
        let location = super::location_in(&rawr_import::location::rawr_directory_here(&root));
        std::fs::create_dir_all(location.parent().expect("the record has a directory"))
            .expect("the directory is written");
        let other = "f".repeat(64);
        std::fs::write(&location, super::encode(&other, &record).expect("encodes"))
            .expect("the record is written");
        assert_eq!(super::kept(&root), Record::default());
        super::adopt(&root).expect("the record is adopted");
        assert_eq!(super::kept(&root), record);
        // Adopted, it is this build's: storing it again changes nothing.
        assert!(!super::store(&root, &record).expect("the record is stored"));
        // A record that names no build stays none.
        let unnamed = serde_json::to_vec(&record).expect("the record encodes");
        std::fs::write(&location, unnamed).expect("the record is written");
        super::adopt(&root).expect("nothing is adopted");
        assert_eq!(super::kept(&root), Record::default());
        std::fs::remove_file(&location).expect("the record is removed");
    }
}
